namespace Tsump.Services;

public class LanguageService
{
    // The secondary language is always English; the primary is club-configurable.
    public const string Secondary = "en";

    // Order is the display order in the language picker.
    public static readonly string[] SupportedLanguages = { "nl", "en", "fr", "de" };

    private string _primary = "nl";   // club's configured primary language
    private string _language = "nl";  // currently displayed language (primary or English)

    public string Language => _language;
    public string PrimaryLanguage => _primary;
    public bool IsDutch => _language == "nl";
    public bool IsEnglish => _language == "en";

    public event Action? OnLanguageChanged;

    private static string Normalize(string? language) =>
        language != null && Array.IndexOf(SupportedLanguages, language) >= 0 ? language : "nl";

    // Called once at startup with the persisted club primary; the active language follows it.
    public void Configure(string? primaryLanguage)
    {
        _primary = Normalize(primaryLanguage);
        _language = _primary;
        OnLanguageChanged?.Invoke();
    }

    // Sets the club's primary language (Settings → Language) and switches the display to it.
    public void SetPrimaryLanguage(string language)
    {
        _primary = Normalize(language);
        _language = _primary;
        OnLanguageChanged?.Invoke();
    }

    // Sets the active display language (the top-row toggle: primary ⇄ English).
    public void SetLanguage(string language)
    {
        var lang = Normalize(language);
        if (_language != lang)
        {
            _language = lang;
            OnLanguageChanged?.Invoke();
        }
    }

    private Dictionary<string, string> ActiveDictionary => _language switch
    {
        "nl" => Dutch,
        "fr" => French,
        "de" => German,
        _ => English,
    };

    public string Get(string key)
    {
        if (ActiveDictionary.TryGetValue(key, out var value))
            return value;
        // Fall back to English, then to the raw key, so a missing translation degrades gracefully.
        if (English.TryGetValue(key, out var en))
            return en;
        return key;
    }

    public string FormatDate(DateTime date)
    {
        var day = Get(date.DayOfWeek.ToString());
        var month = Get($"Month{date.Month}");
        return $"{day} {date.Day} {month} {date.Year}";
    }

